import type { Metadata } from 'next';
import Link from 'next/link';
import fs from 'node:fs';
import path from 'node:path';

/**
 * /benchmarks/coding — the launch asset.
 *
 * Renders whatever the benchmark harness last wrote to
 * public/data/coding-benchmark.json (scripts/benchmarks/coding_benchmark.py in
 * the backend repo, run on a schedule).
 *
 * The page never invents numbers. If no report file exists it says so, rather
 * than rendering placeholders that would read as real results — this page is
 * going to be posted to r/LocalLLaMA and read adversarially, and one fabricated
 * figure discredits everything else on the domain.
 */

export const metadata: Metadata = {
  title: 'Coding-agent benchmark: latency and cost | Gatewayz',
  description:
    'Measured time-to-first-token, throughput and cost for coding-agent workloads through Gatewayz versus calling providers directly. Methodology and raw samples included.',
  keywords: [
    'llm latency benchmark',
    'coding agent benchmark',
    'claude code cost',
    'llm gateway latency',
    'prompt caching savings',
  ],
  alternates: { canonical: 'https://gatewayz.ai/benchmarks/coding' },
};

// Regenerated by the harness; revalidate hourly so a fresh run appears without
// a redeploy.
export const revalidate = 3600;

type SummaryRow = {
  model: string;
  route: string;
  runs: number;
  errors: number;
  ttft_ms_p50: number | null;
  ttft_ms_p95: number | null;
  total_ms_p50: number | null;
  tokens_per_sec_mean: number | null;
  cache_read_tokens_total: number;
  cache_write_tokens_total: number;
};

type Report = {
  generated_at: number;
  summary: Record<string, SummaryRow>;
  warnings: string[];
};

function loadReport(): Report | null {
  try {
    const file = path.join(process.cwd(), 'public', 'data', 'coding-benchmark.json');
    if (!fs.existsSync(file)) return null;
    return JSON.parse(fs.readFileSync(file, 'utf-8')) as Report;
  } catch {
    return null;
  }
}

function fmt(value: number | null, unit = 'ms'): string {
  return value === null || value === undefined ? '—' : `${value}${unit}`;
}

export default function CodingBenchmarkPage() {
  const report = loadReport();
  const rows = report ? Object.values(report.summary) : [];

  return (
    <div className="min-h-screen bg-background pb-24">
      <div className="mx-auto max-w-4xl px-4 py-16 sm:px-6 lg:px-8">
        <header className="mb-10">
          <h1 className="text-4xl font-bold tracking-tight">Coding-agent benchmark</h1>
          <p className="mt-3 text-lg text-muted-foreground">
            Time-to-first-token, throughput and cache behaviour on realistic coding-agent
            workloads — through Gatewayz and directly against the provider.
          </p>
          {report && (
            <p className="mt-2 text-sm text-muted-foreground">
              Last run: {new Date(report.generated_at * 1000).toISOString()}
            </p>
          )}
        </header>

        {!report ? (
          <div className="rounded-xl border border-dashed p-8 text-center">
            <h2 className="text-lg font-semibold">No benchmark run published yet</h2>
            <p className="mt-2 text-sm text-muted-foreground">
              This page renders measured results only. Once the harness has run against
              production, its output appears here.
            </p>
          </div>
        ) : (
          <>
            {report.warnings?.length > 0 && (
              <div className="mb-8 rounded-lg border border-amber-300 bg-amber-50 p-4 dark:border-amber-800 dark:bg-amber-900/20">
                <h2 className="mb-2 text-sm font-semibold">Caveats from this run</h2>
                <ul className="list-disc space-y-1 pl-5 text-sm">
                  {report.warnings.map((w) => (
                    <li key={w}>{w}</li>
                  ))}
                </ul>
              </div>
            )}

            <div className="overflow-x-auto">
              <table className="w-full border-collapse text-sm">
                <thead>
                  <tr className="border-b text-left">
                    <th className="py-3 pr-4 font-semibold">Model</th>
                    <th className="py-3 pr-4 font-semibold">Route</th>
                    <th className="py-3 pr-4 font-semibold">TTFT p50</th>
                    <th className="py-3 pr-4 font-semibold">TTFT p95</th>
                    <th className="py-3 pr-4 font-semibold">Tok/s</th>
                    <th className="py-3 pr-4 font-semibold">Cache reads</th>
                    <th className="py-3 font-semibold">Runs</th>
                  </tr>
                </thead>
                <tbody>
                  {rows.map((row) => (
                    <tr key={`${row.model}-${row.route}`} className="border-b">
                      <td className="py-3 pr-4 font-medium">{row.model}</td>
                      <td className="py-3 pr-4 text-muted-foreground">{row.route}</td>
                      <td className="py-3 pr-4">{fmt(row.ttft_ms_p50)}</td>
                      <td className="py-3 pr-4">{fmt(row.ttft_ms_p95)}</td>
                      <td className="py-3 pr-4">{fmt(row.tokens_per_sec_mean, '')}</td>
                      <td className="py-3 pr-4">
                        {row.cache_read_tokens_total.toLocaleString()}
                      </td>
                      <td className="py-3 text-muted-foreground">
                        {row.runs}
                        {row.errors > 0 && (
                          <span className="ml-1 text-amber-600">({row.errors} failed)</span>
                        )}
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          </>
        )}

        <section className="mt-16 border-t pt-8">
          <h2 className="mb-4 text-xl font-semibold">Methodology</h2>
          <ul className="list-disc space-y-2 pl-5 text-sm text-muted-foreground">
            <li>
              Each task carries a large static system prefix marked with{' '}
              <code>cache_control</code>, plus a short varying instruction — the shape a coding
              agent actually produces.
            </li>
            <li>
              Gateway and direct-provider calls for a task run back to back, so both see
              comparable provider-side load.
            </li>
            <li>
              Time-to-first-token is measured to the first chunk carrying content or a tool call.
              The opening role chunk does not count.
            </li>
            <li>
              p50 and p95 are nearest-rank over successful samples. Failed requests are counted
              separately and never averaged in.
            </li>
            <li>
              If a run produces zero cache reads while sending <code>cache_control</code>, the
              harness emits a warning and no cost-advantage claim is published from it.
            </li>
          </ul>
          <p className="mt-4 text-sm text-muted-foreground">
            Provider latency varies by time of day and load. Treat any single run as a snapshot.
          </p>
        </section>

        <section className="mt-12 border-t pt-8">
          <div className="flex flex-wrap gap-3">
            <Link href="/use" className="rounded-lg border px-4 py-2 text-sm hover:bg-muted">
              Setup guides
            </Link>
            <Link
              href="/compare/gatewayz-vs-openrouter"
              className="rounded-lg border px-4 py-2 text-sm hover:bg-muted"
            >
              Gatewayz vs OpenRouter
            </Link>
          </div>
        </section>
      </div>
    </div>
  );
}
